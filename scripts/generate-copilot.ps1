# Generates GitHub Copilot instructions from skills/*/SKILL.md.
# Claude Code reads skills/ directly (via symlink into ~/.claude/skills) - no generation needed there.
#
# Output:
#   .github/copilot-instructions.md          - index: skill name + description, always loaded by Copilot
#   .github/instructions/<name>.instructions.md - full skill body, one per skill

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$skillsDir = Join-Path $root "skills"
$outDir = Join-Path $root ".github/instructions"
$indexPath = Join-Path $root ".github/copilot-instructions.md"

New-Item -ItemType Directory -Force -Path $outDir | Out-Null

# Remove stale output from skills that were renamed or deleted since the last generation.
Get-ChildItem -Path $outDir -Filter "*.instructions.md" -ErrorAction SilentlyContinue | Remove-Item -Force

function Parse-Frontmatter($content) {
    if ($content -match "(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$") {
        $fm = $Matches[1]
        $body = $Matches[2]
        $name = if ($fm -match "name:\s*(.+)") { $Matches[1].Trim() } else { $null }
        $desc = if ($fm -match "description:\s*(.+)") { $Matches[1].Trim() } else { "" }
        return @{ name = $name; description = $desc; body = $body }
    }
    return @{ name = $null; description = ""; body = $content }
}

$indexLines = @(
    "# Copilot instructions - skill index",
    "",
    "Auto-generated by scripts/generate-copilot.ps1. Do not edit by hand - edit skills/<name>/SKILL.md instead.",
    "",
    "Full skill bodies live in .github/instructions/<name>.instructions.md.",
    ""
)

$skillDirs = Get-ChildItem -Path $skillsDir -Directory | Sort-Object Name

foreach ($dir in $skillDirs) {
    $skillFile = Join-Path $dir.FullName "SKILL.md"
    if (-not (Test-Path $skillFile)) { continue }

    $content = Get-Content -Raw -Path $skillFile
    $parsed = Parse-Frontmatter $content
    $name = if ($parsed.name) { $parsed.name } else { $dir.Name }
    $desc = $parsed.description

    $indexLines += "- **$name** - $desc"

    $outFile = Join-Path $outDir "$name.instructions.md"
    $outContent = @"
---
applyTo: "**"
description: "$desc"
---

<!-- Auto-generated from skills/$($dir.Name)/SKILL.md by scripts/generate-copilot.ps1. Do not edit by hand. -->

$($parsed.body)
"@
    Set-Content -Path $outFile -Value $outContent -NoNewline
}

Set-Content -Path $indexPath -Value ($indexLines -join "`n") -NoNewline

Write-Host "Generated $($skillDirs.Count) instruction files into $outDir"
Write-Host "Generated index at $indexPath"
